"""Provider router for multi-provider AI architecture.

Routes AI requests through Gemini (primary) with local knowledge-based
fallback. Implements bounded exponential backoff with jitter for
transient Gemini errors and does not retry permanent errors.

Records which provider generated each response so the frontend can
display appropriate indicators to users.
"""

import asyncio
import logging
from typing import Any

from app.services.ai.exceptions import (
    AIAuthenticationError,
    AIServiceUnavailableError,
    AITimeoutError,
)
from app.services.ai.local_knowledge import LocalKnowledgeBase, get_knowledge_base
from app.services.ai.providers import (
    AIProvider,
    GeminiProvider,
    LocalFallbackProvider,
    ProviderResult,
    ProviderStatus,
    PROVIDER_GEMINI,
    PROVIDER_LOCAL_FALLBACK,
)

logger = logging.getLogger(__name__)


class ProviderRouter:
    """Routes AI requests through providers with fallback logic.

    Order of precedence:
    1. Gemini (primary) - if configured and available
    2. Local fallback - if Gemini fails or is not configured

    If both providers fail, returns an error result that the frontend
    can display as a graceful user message.

    Tracks which provider was used and whether fallback was triggered.
    """

    def __init__(
        self,
        ai_service: Any,
        knowledge_base: LocalKnowledgeBase | None = None,
        gemini_max_retries: int = 3,
    ) -> None:
        self._gemini = GeminiProvider(ai_service)
        self._local = LocalFallbackProvider(
            knowledge_base or get_knowledge_base()
        )
        self._gemini_max_retries = gemini_max_retries

    @property
    def gemini_provider(self) -> GeminiProvider:
        """Return the Gemini provider instance."""
        return self._gemini

    @property
    def local_provider(self) -> LocalFallbackProvider:
        """Return the local fallback provider instance."""
        return self._local

    async def generate_response(
        self,
        message: str,
        *,
        conversation_history: list[dict[str, str]] | None = None,
        business_context: str | None = None,
        system_instruction: str | None = None,
        temperature: float | None = None,
        max_output_tokens: int | None = None,
    ) -> ProviderResult:
        """Generate a response using the best available provider.

        Attempts Gemini first. If Gemini is unavailable or returns an
        error (after retries for transient errors), falls back to the
        local knowledge-based provider.

        Args:
            message: The user's message text.
            conversation_history: Optional recent conversation turns.
            business_context: Optional business profile context.
            system_instruction: Optional system-level instruction.
            temperature: Sampling temperature.
            max_output_tokens: Maximum output tokens.

        Returns:
            A normalized ProviderResult indicating which provider was
            used and whether fallback was triggered.
        """
        # Stage 1: Try Gemini (primary provider)
        gemini_result = await self._try_gemini(
            message=message,
            conversation_history=conversation_history,
            business_context=business_context,
            system_instruction=system_instruction,
            temperature=temperature,
            max_output_tokens=max_output_tokens,
        )

        if gemini_result.status == ProviderStatus.SUCCESS:
            logger.info(
                "AI response generated by Gemini",
                extra={"provider": PROVIDER_GEMINI, "fallback_used": False},
            )
            return gemini_result

        # Gemini failed - log the reason and fall back
        logger.warning(
            "Gemini provider failed, falling back to local provider",
            extra={
                "provider": PROVIDER_GEMINI,
                "error": gemini_result.error,
                "fallback_to": PROVIDER_LOCAL_FALLBACK,
            },
        )

        # Stage 2: Try local fallback provider
        local_result = await self._local.generate_response(
            message=message,
            conversation_history=conversation_history,
            business_context=business_context,
            system_instruction=system_instruction,
            temperature=temperature,
            max_output_tokens=max_output_tokens,
        )

        if local_result.status == ProviderStatus.SUCCESS:
            # Mark that fallback was used
            local_result.fallback_used = True
            logger.info(
                "AI response generated by local fallback",
                extra={
                    "provider": PROVIDER_LOCAL_FALLBACK,
                    "fallback_used": True,
                    "gemini_error": gemini_result.error,
                },
            )
            return local_result

        # Both providers failed - return error result
        logger.error(
            "Both Gemini and local fallback providers failed",
            extra={
                "gemini_error": gemini_result.error,
                "local_error": local_result.error,
            },
        )
        return ProviderResult(
            text=local_result.text
            or "I'm sorry, I couldn't generate a response at this time. "
            "Please try again later or consult official government websites directly.",
            provider=PROVIDER_LOCAL_FALLBACK,
            status=ProviderStatus.ERROR,
            fallback_used=True,
            requires_verification=True,
            error=(
                f"Gemini: {gemini_result.error}; "
                f"Local: {local_result.error or 'unknown error'}"
            ),
            warnings=[
                "Both AI service and local knowledge base are unavailable. "
                "Please try again later."
            ],
        )

    async def _try_gemini(
        self,
        message: str,
        *,
        conversation_history: list[dict[str, str]] | None = None,
        business_context: str | None = None,
        system_instruction: str | None = None,
        temperature: float | None = None,
        max_output_tokens: int | None = None,
    ) -> ProviderResult:
        """Attempt to generate a response via Gemini.

        If Gemini is not configured/available, returns an error result
        immediately without attempting the call (to avoid unnecessary
        latency).

        Retries transient errors with bounded exponential backoff.
        Does not retry permanent errors (invalid key, auth failure).
        """
        # Quick availability check before attempting
        if not self._gemini.is_available():
            return ProviderResult(
                text="",
                provider=PROVIDER_GEMINI,
                status=ProviderStatus.ERROR,
                error=(
                    "Gemini service is not configured or disabled. "
                    "Set GEMINI_API_KEY and GEMINI_ENABLED=true to enable."
                ),
                fallback_used=False,
            )

        # Attempt with retry logic
        last_error: Exception | None = None
        for attempt in range(self._gemini_max_retries + 1):
            try:
                result = await self._gemini.generate_response(
                    message=message,
                    conversation_history=conversation_history,
                    business_context=business_context,
                    system_instruction=system_instruction,
                    temperature=temperature,
                    max_output_tokens=max_output_tokens,
                )

                if result.status == ProviderStatus.SUCCESS:
                    return result

                # Check if the error is permanent (don't retry)
                if result.error:
                    error_lower = result.error.lower()
                    if any(
                        term in error_lower
                        for term in [
                            "api key",
                            "authentication",
                            "unauthorized",
                            "invalid argument",
                            "bad request",
                            "model not found",
                            "forbidden",
                        ]
                    ):
                        return result  # Permanent error, don't retry

                last_error = Exception(result.error or "Unknown Gemini error")

            except AIServiceUnavailableError as exc:
                # Permanent: not configured - don't retry
                return ProviderResult(
                    text="",
                    provider=PROVIDER_GEMINI,
                    status=ProviderStatus.ERROR,
                    error=str(exc),
                    fallback_used=False,
                )
            except AIAuthenticationError as exc:
                # Permanent: invalid key - don't retry
                return ProviderResult(
                    text="",
                    provider=PROVIDER_GEMINI,
                    status=ProviderStatus.ERROR,
                    error=str(exc),
                    fallback_used=False,
                )
            except (AITimeoutError, Exception) as exc:
                last_error = exc
                if attempt == self._gemini_max_retries:
                    return ProviderResult(
                        text="",
                        provider=PROVIDER_GEMINI,
                        status=ProviderStatus.ERROR,
                        error=str(exc),
                        fallback_used=False,
                    )
                await asyncio.sleep(
                    min(2 ** attempt, 30) + (attempt * 0.1)
                )

        return ProviderResult(
            text="",
            provider=PROVIDER_GEMINI,
            status=ProviderStatus.ERROR,
            error=str(last_error or "Unknown Gemini error"),
            fallback_used=False,
        )

    def get_provider_status(self) -> dict[str, Any]:
        """Return availability status of all providers.

        Useful for health checks and debugging without leaking
        sensitive configuration.
        """
        return {
            "gemini": {
                "available": self._gemini.is_available(),
                "provider": PROVIDER_GEMINI,
            },
            "local_fallback": {
                "available": self._local.is_available(),
                "provider": PROVIDER_LOCAL_FALLBACK,
            },
            "fallback_enabled": True,
        }


__all__ = [
    "ProviderRouter",
    "PROVIDER_GEMINI",
    "PROVIDER_LOCAL_FALLBACK",
]
